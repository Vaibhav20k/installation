/**
 * CSV exports. Each export runs the same scoped, filtered server query as its screen and carries
 * the window, versions and provisional status. Formula-like text is escaped.
 */
import { cookies } from "next/headers";
import { getDb } from "@/server/db/client";
import { DEMO_COOKIE, resolveActor } from "@/server/auth/actor";
import { AppError, HTTP_STATUS, toAppError } from "@/server/errors";
import { requireRole } from "@/server/auth/permissions";
import { planningSheet } from "@/server/queries/planning";
import { installationTracker, issuesTracker, manpowerTracker } from "@/server/queries/trackers";
import { costTracker, ftrTracker } from "@/server/queries/trackers-quality-cost";
import { kraReview } from "@/server/queries/kra";
import { toCsv } from "@/lib/csv";
import { localDateOf, monthOf } from "@/lib/dates";

export const dynamic = "force-dynamic";

export async function GET(req: Request, { params }: { params: Promise<{ view: string }> }) {
  const { view } = await params;
  const url = new URL(req.url);
  const projectId = url.searchParams.get("project") || undefined;
  const now = Date.now();
  const month = /^\d{4}-\d{2}$/.test(url.searchParams.get("month") ?? "") ? url.searchParams.get("month")! : monthOf(localDateOf(now, "Asia/Kolkata"));
  try {
    const db = await getDb();
    const actor = await resolveActor(db, (await cookies()).get(DEMO_COOKIE)?.value);
    // Internal cost, staffing and KRA exports are for supervisors and above; issues and productivity carry no money.
    if (["sheet", "cost", "ftr", "kra"].includes(view)) requireRole(actor, "supervisor", "internal report exports");
    const meta: Array<[string, string]> = [["Generated", new Date(now).toISOString()], ["Generated by", `${actor.name} (${actor.businessId})`], ["Data", "Demo/fictional records; provisional values are labelled"]];
    let headers: string[] = [], rows: unknown[][] = [], title = view;
    if (view === "sheet") {
      const data = (await planningSheet(db, actor, { projectId, status: url.searchParams.get("status") || undefined }, now)).filter((r) => url.searchParams.get("conflicts") !== "1" || r.conflicts.length);
      title = "Management planning sheet";
      headers = ["Visit ID", "Customer ID", "Project ID", "Order IDs", "Products/components", "Site", "Manager", "Visit type", "Approval", "Revision", "Execution status", "Skill requirement", "Requested start", "Requested start meaning", "Departure (UTC)", "Planned start", "Planned end", "Return (UTC)", "Work person-days", "Team", "Staffed", "Team size", "Continuity", "Clearances", "Estimate (paise)", "Project budget (paise)", "Conflicts", "Next action", "Owner", "Due"];
      rows = data.map((r) => [r.visit, r.customerId, r.projectBid, r.orders, r.products, r.site, r.manager, r.visitType, r.approval, r.revision, r.execStatus, r.skills, r.requestedStart, r.requestedMeaning,
        r.departure ? new Date(r.departure).toISOString() : "", r.plannedStart, r.plannedEnd, r.returnAt ? new Date(r.returnAt).toISOString() : "", r.workPersonDays, r.team, r.staffed, r.teamSize, r.continuity,
        r.clearances, r.estimateMinor, r.budgetMinor, r.conflicts.join("; "), r.nextAction, r.owner, r.due]);
      meta.push(["Row grain", "One visit per row; employee allocations are not multiplied into totals"]);
    } else if (view === "kra") {
      const k = await kraReview(db, actor, { month }, now);
      title = "KRA review";
      headers = ["KPI", "Name", "Definition version", "Definition status", "Unit", "Direction", "Baseline (reference text)", "Target (reference text)", "Target status", "Actual", "Detail", "Coverage", "Variance", "Status", "Missing evidence", "Owner"];
      rows = k.rows.map((r) => [r.code, r.name, r.definitionVersion, r.definitionStatus, r.unit, r.direction, r.baselineText, r.targetText, r.targetStatus, r.actual, r.actualDetail, r.coverage, r.variance, r.status, r.missingEvidence.join("; "), r.owner]);
      meta.push(["Window", `${k.period.from} to ${k.period.to} (Asia/Kolkata)`]);
    } else {
      const loaders: Record<string, () => Promise<{ title: string; sourceRange: string; columns: Array<{ key: string; label: string }>; rows: Array<Record<string, unknown>>; notes: string[] }>> = {
        installation: () => installationTracker(db, actor, { projectId }, now),
        manpower: () => manpowerTracker(db, actor, { month, projectId }),
        ftr: () => ftrTracker(db, actor, { projectId }),
        cost: () => costTracker(db, actor, { month, projectId }),
        issues: () => issuesTracker(db, actor, { projectId }),
      };
      const load = loaders[view];
      if (!load) return new Response("Unknown export", { status: 404 });
      const t = await load();
      title = t.title;
      headers = t.columns.map((c) => c.label);
      rows = t.rows.map((r) => t.columns.map((c) => r[c.key]));
      meta.push(["Workbook source", t.sourceRange], ["Window", ["manpower", "cost"].includes(view) ? month : "All records in scope"], ...t.notes.map((n, i) => [`Note ${i + 1}`, n] as [string, string]));
    }
    if (projectId) meta.push(["Project filter", projectId]);
    const body = toCsv(headers, rows, [["View", title], ...meta]);
    return new Response(body, { headers: { "content-type": "text/csv; charset=utf-8", "content-disposition": `attachment; filename="${view}-${month}.csv"`, "cache-control": "no-store" } });
  } catch (e) {
    const err = e instanceof AppError ? e : toAppError(e);
    return new Response(err.message, { status: HTTP_STATUS[err.kind] });
  }
}
